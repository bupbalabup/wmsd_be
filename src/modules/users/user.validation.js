import { z } from 'zod';
import { objectIdString as oid } from '../../shared/utils/domain.js';
import { requestEmailOtpBody, confirmEmailBody } from '../auth/auth.validation.js';

// Vietnamese phone: 0xxxxxxxxx or +84xxxxxxxxx (9-10 digits after the prefix); spaces, dots and dashes are ignored.
const PHONE_RE = /^(0|\+84)\d{9,10}$/;
const phone = z.string().trim().max(30).transform((v) => v.replace(/[\s.-]/g, ''))
  .refine((v) => v === '' || PHONE_RE.test(v), 'Số điện thoại không hợp lệ (ví dụ 0912 345 678 hoặc +84912345678)');
const username = z.string().trim().min(3, 'Tên đăng nhập tối thiểu 3 ký tự').max(50, 'Tên đăng nhập tối đa 50 ký tự')
  .regex(/^[A-Za-z0-9._-]+$/, 'Tên đăng nhập chỉ gồm chữ không dấu, số, dấu chấm, gạch dưới hoặc gạch ngang');

export const listUsersSchema = z.object({
  query: z.object({
    page: z.string().optional(),
    limit: z.string().optional(),
    search: z.string().optional(),
    role: z.string().optional(),
    status: z.enum(['active', 'inactive', 'all']).optional(),
  }),
});

export const createUserSchema = z.object({
  body: z.strictObject({
    username,
    fullName: z.string().min(2, 'Họ và tên tối thiểu 2 ký tự'),
    roleCode: z.string().trim().min(1).max(60),
    phone: phone.optional(),
    // The initial password is generated by the server and emailed to this address.
    email: z.email('Email không hợp lệ').max(254), warehouseIds:z.array(oid).max(100).refine(ids=>new Set(ids).size===ids.length).optional(),
    isActive: z.boolean().optional(),
  }),
});

export const updateUserSchema = z.object({
  params: z.object({
    id: z.string(),
  }),
  body: z.strictObject({
    fullName: z.string().min(2).optional(),
    roleCode: z.string().trim().min(1).max(60).optional(),
    phone: phone.optional(),
    // Email is no longer accepted here: it changes only through the OTP flow (POST /users/:id/email/otp).
    warehouseIds:z.array(oid).max(100).refine(ids=>new Set(ids).size===ids.length).optional(),
  }),
});

export const toggleStatusSchema = z.object({
  params: z.object({
    id: z.string(),
  }),
  body: z.object({
    isActive: z.boolean(),
    reason: z.string().trim().min(1).max(2000).optional(),
  }).refine(value => value.isActive || !!value.reason, { message: 'Cần nhập lý do khóa tài khoản', path: ['reason'] }),
});

export const requestUserEmailOtpSchema = z.object({ params: z.object({ id: oid }), body: requestEmailOtpBody });
export const confirmUserEmailSchema = z.object({ params: z.object({ id: oid }), body: confirmEmailBody });
